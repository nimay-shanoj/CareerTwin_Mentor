"""Download the Google Fonts woff2 files and write a local @font-face sheet.

The pages used to pull Poppins and DM Sans from fonts.googleapis.com with a
render-blocking <link>.  On a LAN - or on a phone - that request can take
seconds or time out completely, and the page cannot paint until it answers.

Self-hosting removes the third-party dependency completely: the fonts are
served by the same Flask process, the demo works with no internet, and there
is nothing left to block the first paint.
"""

import os
import re
import sys
import urllib.request

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FONT_DIR = os.path.join(ROOT, "static", "fonts")
CSS_OUT = os.path.join(ROOT, "static", "css", "fonts.css")

# A modern browser User-Agent makes the API serve woff2 instead of ttf.
UA = (
    "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 "
    "(KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36"
)

FAMILIES = [
    ("DM Sans", "400;500;700"),
    ("Poppins", "600;700;800"),
]

SHEET_HEADER = """/* ==========================================================================
   fonts.css - self-hosted web fonts.

   Generated by tools/fetch_fonts.py - do not edit by hand.

   Poppins and DM Sans are licensed under the SIL Open Font License 1.1.
   ========================================================================== */

"""


def fetch(url, accept=None):
    request = urllib.request.Request(url)
    request.add_header("User-Agent", UA)
    if accept:
        request.add_header("Accept", accept)
    with urllib.request.urlopen(request, timeout=60) as response:
        return response.read()


def main():
    os.makedirs(FONT_DIR, exist_ok=True)
    url = (
        "https://fonts.googleapis.com/css2?"
        + "&".join(
            f"family={name.replace(' ', '+')}:wght@{weights}"
            for name, weights in FAMILIES
        )
        + "&display=swap"
    )
    css = fetch(url).decode("utf-8")

    # Each @font-face block: family, weight, style, and the woff2 url.
    blocks = re.findall(r"@font-face\s*\{[^}]*\}", css)
    print(f"the API returned {len(blocks)} @font-face blocks")

    out = [SHEET_HEADER]
    seen = set()

    # Google returns one @font-face per unicode subset (latin-ext, greek,
    # latin, …). The one we want is the block whose unicode-range covers
    # U+0000-00FF - basic Latin. Picking the first block would give us a
    # subset without the letters we actually need.
    candidates = {}
    for block in blocks:
        family = re.search(r"font-family:\s*'([^']+)'", block)
        weight = re.search(r"font-weight:\s*(\d+)", block)
        style = re.search(r"font-style:\s*(\w+)", block)
        url_match = re.search(r"url\((https://[^)]+\.woff2)\)", block)
        if not (family and weight and url_match):
            continue

        key = (family.group(1), weight.group(1))
        entry = {
            "family": family.group(1),
            "weight": weight.group(1),
            "style": style.group(1) if style else "normal",
            "url": url_match.group(1),
            "range": "",
        }
        range_match = re.search(r"unicode-range:\s*([^;]+);", block)
        if range_match:
            entry["range"] = range_match.group(1)

        previous = candidates.get(key)
        is_latin = "U+0000-00FF" in entry["range"]
        was_latin = previous and "U+0000-00FF" in previous["range"]
        if previous is None or (is_latin and not was_latin):
            candidates[key] = entry

    for (family, weight), entry in candidates.items():
        name = family
        weight_value = weight
        style_value = entry["style"]
        source = entry["url"]

        filename = f"{name.replace(' ', '')}-{weight_value}.woff2"
        if filename in seen:
            continue
        seen.add(filename)

        path = os.path.join(FONT_DIR, filename)
        if not os.path.exists(path):
            data = fetch(source, accept="font/woff2")
            with open(path, "wb") as handle:
                handle.write(data)
            print(f"  downloaded {filename}  ({len(data) / 1024:.0f} KB)")

        out.append(
            "@font-face {\n"
            f'  font-family: "{name}";\n'
            f"  font-style: {style_value};\n"
            f"  font-weight: {weight_value};\n"
            "  font-display: swap;\n"
            f'  src: url("/static/fonts/{filename}") format("woff2");\n'
            "}\n\n"
        )

    with open(CSS_OUT, "w", encoding="utf-8", newline="\n") as handle:
        handle.write("".join(out))

    total = sum(
        os.path.getsize(os.path.join(FONT_DIR, f)) for f in os.listdir(FONT_DIR)
    )
    print(f"\nwrote {CSS_OUT}")
    print(f"  {len(seen)} font files, {total / 1024:.0f} KB total")
    return 0


if __name__ == "__main__":
    sys.exit(main())
